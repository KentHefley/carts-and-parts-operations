import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { developmentCredentials } from "./development-target";
import { createDatabaseClient } from "../lib/database-client";
import { mutateComment, readComments } from "../lib/comment-store";
import { reserveOrder, saveOrder, loadOrder, copyOrder } from "../lib/order-store";
import { trashOrder, restoreOrder, purgeExpiredOrders } from "../lib/trash-store";
import type { AttachmentStorage } from "../lib/attachment-storage";
async function main() {
  const db = createDatabaseClient(developmentCredentials().databaseUrl);
  const [author, other, admin, inactive, outsider] = Array.from({ length: 5 }, () => randomUUID());
  const accountIds = [author, other, admin, inactive, outsider];
  const orderIds: string[] = [];
  const fake: AttachmentStorage = { upload: async () => { throw Error("not used"); }, inspect: async () => { throw Error("not used"); }, promote: async () => { throw Error("not used"); }, remove: async () => {}, read: async () => { throw Error("not used"); } };
  try {
    await db.appUser.createMany({ data: accountIds.map((id, index) => ({ id, clerkUserId: `synthetic-comments-${id}`, email: `${id}@example.invalid`, displayName: `Comment Tester ${index}`, role: id === admin ? "ADMIN" as const : "USER" as const, active: id !== inactive })) });
    let order = await reserveOrder(db, author, randomUUID()); orderIds.push(order.id);
    const saved = await saveOrder(db, author, { id: order.id, base: order.fields, patch: { name: "Synthetic comments verification" } });
    assert.equal(saved.ok, true); if (!saved.ok) throw Error("Fixture save failed"); order = saved.order;
    await db.orderAssignment.createMany({ data: [author, other, admin, inactive].map(userId => ({ orderId: order.id, userId })) });
    await db.notification.deleteMany({ where: { orderId: order.id } });
    const input = { operation: "add" as const, orderId: order.id, requestKey: randomUUID(), text: "Original <script>plain text</script>\nSecond line", mentionIds: [other.toUpperCase()] };
    const [id, repeated] = await Promise.all([mutateComment(db, author, input), mutateComment(db, author, input)]);
    assert.equal(id, repeated);
    assert.equal(await db.orderComment.count({ where: { orderId: order.id } }), 1);
    const alerts = await db.notification.findMany({ where: { orderId: order.id } });
    assert.equal(new Set(alerts.map(row => row.recipientId)).size, alerts.length);
    assert.equal(alerts.find(row => row.recipientId === other)?.kind, "mention");
    assert.equal(alerts.find(row => row.recipientId === admin)?.kind, "comment");
    assert.equal(alerts.some(row => row.recipientId === author || row.recipientId === inactive), false);
    assert.equal(alerts.some(row => row.recipientId === outsider), false);
    assert.equal(alerts.length, 2);
    const mentionedOutsider = await mutateComment(db, author, { ...input, requestKey: randomUUID(), text: "Explicitly mentioned unassigned employee", mentionIds: [outsider] });
    const targeted = await db.notification.findMany({ where: { orderId: order.id, id: { notIn: alerts.map(row => row.id) } } });
    assert.equal(targeted.length, 3);
    assert.equal(targeted.find(row => row.recipientId === outsider)?.kind, "mention");
    await mutateComment(db, author, { operation: "delete", orderId: order.id, id: mentionedOutsider, version: 1 });
    const expectedAlertCount = alerts.length + targeted.length;
    await assert.rejects(mutateComment(db, author, { ...input, text: "different payload, same key" }), /different content/);
    await assert.rejects(mutateComment(db, inactive, { ...input, requestKey: randomUUID() }), /approved access/);
    await assert.rejects(readComments(db, inactive, order.id), /approved access/);
    await assert.rejects(mutateComment(db, author, { ...input, requestKey: randomUUID(), mentionIds: [inactive] }), /no longer active/);
    await assert.rejects(mutateComment(db, author, { ...input, requestKey: randomUUID(), text: "  " }), /Enter a comment/);
    await assert.rejects(mutateComment(db, author, { ...input, requestKey: randomUUID(), mentionIds: [other, other] }), /distinct/);
    await assert.rejects(mutateComment(db, other, { operation: "edit", orderId: order.id, id, version: 1, text: "Not allowed", mentionIds: [] }), /Only the author/);
    await assert.rejects(mutateComment(db, other, { operation: "delete", orderId: order.id, id, version: 1 }), /Only the author/);
    await mutateComment(db, author, { operation: "edit", orderId: order.id, id, version: 1, text: "Author revision", mentionIds: [other] });
    await assert.rejects(mutateComment(db, author, { operation: "edit", orderId: order.id, id, version: 1, text: "Stale revision", mentionIds: [] }), /Someone else changed/);
    await mutateComment(db, admin, { operation: "edit", orderId: order.id, id, version: 2, text: "Admin revision", mentionIds: [other] });
    const edited = await db.orderComment.findUniqueOrThrow({ where: { id } });
    assert.equal(edited.authorId, author); assert.equal(edited.authorName, "Comment Tester 0"); assert.ok(edited.editedAt);
    assert.equal(edited.version, 3);
    await assert.rejects(mutateComment(db, admin, { operation: "delete", orderId: order.id, id, version: 2 }), /Someone else changed/);
    await mutateComment(db, admin, { operation: "delete", orderId: order.id, id, version: 3 });
    await mutateComment(db, admin, { operation: "delete", orderId: order.id, id, version: 3 });
    assert.equal(await mutateComment(db, author, input), id);
    assert.equal((await readComments(db, author, order.id)).rows.length, 0);
    assert.equal(await db.notification.count({ where: { orderId: order.id } }), expectedAlertCount);
    const deleted = await db.orderComment.findUniqueOrThrow({ where: { id } });
    assert.equal(deleted.text, ""); assert.ok(deleted.deletedAt);
    const history = await db.orderEvent.findMany({ where: { orderId: order.id, changes: { path: ["commentId"], equals: id } }, orderBy: { createdAt: "asc" } });
    assert.equal(history.length, 4); assert.match(JSON.stringify(history), /Original <script>plain text/); assert.match(JSON.stringify(history), /Author revision/); assert.match(JSON.stringify(history), /Admin revision/);
    const retained = await mutateComment(db, author, { ...input, requestKey: randomUUID(), text: "Retained through Trash and restore" });
    const copied = await copyOrder(db, author, await loadOrder(db, order.id), randomUUID());
    assert.equal(copied.ok, true); if (!copied.ok) throw Error("Copy fixture failed"); orderIds.push(copied.order.id);
    assert.equal(await db.orderComment.count({ where: { orderId: copied.order.id } }), 0);
    await assert.rejects(mutateComment(db, admin, { operation: "delete", orderId: copied.order.id, id: retained, version: 1 }), /Only the author/);
    await assert.rejects(readComments(db, admin, copied.order.id, retained), /page not found/);
    // Fixture rows exercise paging without generating dozens of bell alerts.
    const now = Date.now();
    await db.orderComment.createMany({ data: Array.from({ length: 51 }, (_, index) => ({ orderId: order.id, authorId: author, authorName: "Comment Tester 0", requestKey: randomUUID(), requestHash: "synthetic-pagination-only", text: `Page comment ${index}`, createdAt: new Date(now + index) })) });
    const first = await readComments(db, other, order.id); assert.equal(first.rows.length, 50); assert.ok(first.nextCursor);
    const second = await readComments(db, other, order.id, first.nextCursor); assert.equal(second.rows.length, 2); assert.equal(second.nextCursor, undefined);
    assert.equal(new Set([...first.rows, ...second.rows].map(row => row.id)).size, 52);
    const cursorComment = first.rows.at(-1)!;
    await mutateComment(db, author, { operation: "delete", orderId: order.id, id: cursorComment.id, version: cursorComment.version });
    assert.deepEqual((await readComments(db, other, order.id, first.nextCursor)).rows.map(row => row.id), second.rows.map(row => row.id));
    await trashOrder(db, author, order.id);
    await assert.rejects(readComments(db, author, order.id), /outside Trash/);
    await assert.rejects(mutateComment(db, author, { ...input, requestKey: randomUUID() }), /outside Trash/);
    await restoreOrder(db, admin, order.id);
    assert.equal((await db.orderComment.findUniqueOrThrow({ where: { id: retained } })).text, "Retained through Trash and restore");
    await trashOrder(db, author, order.id);
    await db.salesOrder.update({ where: { id: order.id }, data: { purgeAfter: new Date(Date.now() - 1) } });
    assert.equal((await purgeExpiredOrders(db, fake, order.id)).purged, 1);
    assert.equal(await db.orderComment.count({ where: { orderId: order.id } }), 0);
    assert.equal(await db.orderEvent.count({ where: { orderId: order.id } }), 0);
    console.log("Comments passed: permissions, concurrent deduplication, mentions/general alerts, inactive denial, stale edit/delete, original-author audit, deletion non-resurrection, paging, copies, Trash restore and purge. No emails sent.");
  } finally {
    await db.notification.deleteMany({ where: { OR: [{ orderId: { in: orderIds } }, { actorId: { in: accountIds } }, { recipientId: { in: accountIds } }] } });
    await db.orderComment.deleteMany({ where: { orderId: { in: orderIds } } });
    await db.orderAssignment.deleteMany({ where: { orderId: { in: orderIds } } });
    await db.orderEvent.deleteMany({ where: { orderId: { in: orderIds } } });
    await db.orderItem.deleteMany({ where: { orderId: { in: orderIds } } });
    await db.salesOrder.deleteMany({ where: { id: { in: orderIds } } });
    await db.appUser.deleteMany({ where: { id: { in: accountIds } } });
    await db.$disconnect();
  }
}
main().catch(error => { console.error(error instanceof Error ? error.message : "Comment test failed."); process.exitCode = 1; });
